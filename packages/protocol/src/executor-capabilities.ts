export const InstancePermissionSchema = v.variant("ceiling", [
  v.strictObject({ ceiling: v.literal("ask"), selected: v.literal("ask") }),
  v.strictObject({ ceiling: v.literal("edits"), selected: v.picklist(["ask", "edits"]) }),
  v.strictObject({ ceiling: v.literal("open"), selected: PermissionModeSchema }),
]);
export type InstancePermission = v.InferOutput<typeof InstancePermissionSchema>;
/** The environment selects the current snapshot for each configured executor instance. */
export const ExecutorCapabilitiesSchema = v.strictObject({
  instanceId: ExecutorInstanceIdSchema,
  family: AdapterFamilySchema,
  version: v.pipe(v.number(), v.safeInteger(), v.minValue(0), v.maxValue(Number.MAX_SAFE_INTEGER)),
  checkedAt: v.pipe(
    v.number(),
    v.safeInteger(),
    v.minValue(0),
    v.maxValue(Number.MAX_SAFE_INTEGER),
  ),
  matrix: CapabilityMatrixSchema,
  permission: v.optional(InstancePermissionSchema),
  textGeneration: v.optional(CapabilitySupportSchema),
});
export type ExecutorCapabilities = v.InferOutput<typeof ExecutorCapabilitiesSchema>;

/** A fresh snapshot includes the effective configuration. Older published snapshots may lack it. */
export const ExecutorInstanceSnapshotSchema = v.strictObject({
  ...ExecutorCapabilitiesSchema.entries,
  permission: InstancePermissionSchema,
});
export type ExecutorInstanceSnapshot = v.InferOutput<typeof ExecutorInstanceSnapshotSchema>;
